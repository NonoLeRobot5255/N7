import java.util.Arrays;
import org.apache.log4j.Level;
import org.apache.log4j.Logger;
import org.apache.spark.SparkConf;
import org.apache.spark.streaming.Durations;
import org.apache.spark.streaming.api.java.JavaDStream;
import org.apache.spark.streaming.api.java.JavaPairDStream;
import org.apache.spark.streaming.api.java.JavaReceiverInputDStream;
import org.apache.spark.streaming.api.java.JavaStreamingContext;
import scala.Tuple2;

public class CpuMean {
    public static void main(String args[]) {

        Logger.getLogger("org").setLevel(Level.OFF);
        Logger.getLogger("akka").setLevel(Level.OFF);
        // Create the context with a 1 second batch size
        SparkConf sparkConf = new SparkConf().setAppName("CpuMean");
        JavaStreamingContext ssc = new JavaStreamingContext(sparkConf, Durations.seconds(1));
        // Create a JavaReceiverInputDStream on target ip:port and count the
        // words in input stream of \n delimited text (eg. generated by 'nc')

        ssc.checkpoint(".");
        JavaReceiverInputDStream<String> lines = ssc.socketTextStream("localhost", 9999);
        JavaPairDStream<String, Tuple2<Double, Integer>> sums = lines
                .mapToPair(s -> {
                    String[] parts = s.trim().split("\\s+");
                    return new Tuple2<>(parts[0], new Tuple2<>(Double.parseDouble(parts[1]), 1));
                })
                .reduceByKeyAndWindow(
                        (a, b) -> new Tuple2<>(a._1() + b._1(), a._2() + b._2()),
                        Durations.seconds(10),
                        Durations.seconds(5));

        JavaPairDStream<String, Double> means = sums.mapValues(t -> t._1() / t._2());

        means.print();
        ssc.start();
        try {
            ssc.awaitTermination();
        } catch (InterruptedException e) {
            e.printStackTrace();
        }
    }
}